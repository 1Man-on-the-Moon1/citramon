def get_city_display_name(city_ru: str, lang: str) -> str:
    """Get localized city name. Falls back to Russian."""
    if lang == 'ru':
        return city_ru
    translations = CITY_TRANSLATIONS.get(city_ru)
    if translations and lang in translations:
        return translations[lang]
    return city_ru


def get_city_ru_from_display(display_name: str, lang: str, country_cities: list) -> str | None:
    """Reverse lookup: find Russian city key from localized display name."""
    if lang == 'ru':
        return display_name if display_name in country_cities else None
    for city_ru in country_cities:
        translations = CITY_TRANSLATIONS.get(city_ru, {})
        if translations.get(lang) == display_name:
            return city_ru
    # Fallback: check if it's already Russian
    if display_name in country_cities:
        return display_name
    return None
